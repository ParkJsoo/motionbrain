"""Dual-camera acquisition for the fixed M4 trial; no motor access or retries."""
from __future__ import annotations

import copy
import hashlib
from pathlib import Path
import time

import cv2
import numpy as np

from learning.action_recorder import ActionRecorder
from learning.artifacts import ArtifactStore, _decode_json, _read
from learning.grasp_observation import GripperObservationSource
from learning.lossless_frame import decode
from learning.manual_collection_dataset import require


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


class M4DualCameraObserver:
    """Reuse native recording and fresh ESP capture, with explicit review.

    reviewer(request, *, deadline, tick) returns context/stable/onsite. It must
    honor the deadline and call tick while waiting. No affirmative physical
    judgment is generated by this adapter. Construction never captures.
    """
    def __init__(self, scope, config, store, reviewer, *, clock=time):
        require(callable(reviewer), 'explicit_dual_camera_reviewer_required')
        require(set(config) == {'helperPath','helperSha256','cameraUrl'}, 'm4_camera_config_fields')
        require(sha(Path(config['helperPath']).read_bytes()) == config['helperSha256'], 'm4_camera_helper_changed')
        self.scope, self.config = copy.deepcopy(scope), copy.deepcopy(config)
        self.store, self.reviewer, self.clock = store, reviewer, clock
        ctx = scope['context']
        plan = dict(deviceId=ctx['externalDeviceId'], viewId=ctx['externalViewId'],
                    sessionId=scope['hostClockId'], hostClockId=scope['hostClockId'],
                    maxFrames=500, seconds=90, sampleFps=4, maxBytes=4200000000,
                    width=1920, height=1080)
        self.recorder = ActionRecorder(store.root/'external', config['helperPath'], plan, clock=clock)
        self.gripper = None
        self.cached = self.closed = None
        self.started = self.failed = False
        self.labels = set()

    def start(self, *, deadline):
        require(not self.started and self.clock.monotonic() < deadline, 'm4_camera_start_invalid')
        require(sha(Path(self.config['helperPath']).read_bytes()) == self.config['helperSha256'], 'm4_camera_helper_changed')
        self.started = True
        # Set started first so partial native startup is also closed by the owner.
        self.recorder.start()
        ctx = self.scope['context']
        scene = {k: ctx[k] for k in ('physicalView','object','poseRegime')}
        scene['landmarks'] = 'M4 commissioning dual-camera review; no learned state'
        self.gripper = GripperObservationSource(self.config['cameraUrl'], self.scope['hostClockId'],
            ctx['gripperCameraBootId'], scene, ArtifactStore(self.store.root/'gripper-source'),
            max_captures=2, clock=self.clock)
        self.gripper.start(deadline=deadline)

    def _wait(self, predicate, deadline, tick):
        while self.clock.monotonic() < deadline:
            tick()
            value = predicate()
            if value is not None: return value
            self.clock.sleep(.05)
        raise ValueError('m4_camera_wait_expired')

    def _external(self, not_before, deadline, tick):
        def select():
            with self.recorder.lock:
                require(not self.recorder.fault and not self.recorder.done, 'm4_native_stream_failed')
                if not self.recorder.frames: return None
                self.recorder.check()
                for frame in reversed(self.recorder.frames):
                    ready_at = frame['stdoutReadAt']+frame['persistenceMs']/1000
                    if (not frame['qualityFlags'] and frame['sourceEarliest'] >= not_before
                            and ready_at <= self.clock.monotonic()-.15):
                        return copy.deepcopy(frame)
        return self._wait(select, deadline, tick)

    def wait_pre_window(self, *, deadline, tick):
        def ready():
            with self.recorder.lock:
                if not self.recorder.frames: return None
                first=self.recorder.frames[0]['sourceEarliest']
                return True if self.clock.monotonic()>=first+3.6 else None
        return self._wait(ready,deadline,tick)

    def wait_post_window(self, after_off, *, deadline, tick):
        return self._wait(lambda: True if self.clock.monotonic()>=after_off+6.4 else None,deadline,tick)

    def observe(self, *, after_off, deadline, tick):
        require(self.started and self.closed is None and not self.failed, 'm4_camera_not_active')
        label = 'before' if after_off is None else 'after'
        require(label not in self.labels and (label == 'before' or 'before' in self.labels), 'm4_camera_no_retake')
        self.labels.add(label)  # A failed capture consumes this label too.
        try:
            threshold = self.recorder.started if after_off is None else after_off+3.
            if after_off is not None:
                self._wait(lambda: True if self.clock.monotonic() >= threshold else None, deadline, tick)
            # One fresh request; this source saves bytes even on capture failure.
            tick()
            record = self.gripper.capture(deadline=deadline)
            self.gripper.verify(record)
            binding = self.gripper._bindings[record['frame']['frameId']]
            folder = binding['folder']
            meta = _read(self.gripper.store.root, folder+'/esp32-frame.json')
            image = _read(self.gripper.store.root, folder+'/esp32-frame.jpg')
            self.store._write(f'gripper/esp32-{label}.jpg', image)
            self.store._write(f'gripper/esp32-{label}.json', meta)
            frame = self._external(threshold, min(deadline, self.clock.monotonic()+15.), tick)
            native_raw = _read(self.recorder.root/'host-ingress', f"{frame['frameIndex']:04d}.json")
            require(_decode_json(native_raw) == frame, 'm4_native_binding_changed')
            pixels = decode(_read(self.recorder.root, frame['imageFile']), frame['rawByteLength'], frame['pixelSha256'])
            preview = np.frombuffer(pixels,np.uint8).reshape(frame['height'],frame['width'],4)
            ok, png = cv2.imencode('.png',preview)
            require(ok, 'm4_native_preview_failed')
            self.store._write(f'{label}-external.png',png.tobytes())
            self.store._write(f'{label}-gripper.jpg',image)
            sources = dict(external=dict(root='external', ingressFile=f"host-ingress/{frame['frameIndex']:04d}.json",
                               ingressSha256=sha(native_raw), clockSha256=sha(_read(self.recorder.root/'host-ingress','clock-before.json'))),
                           gripper=dict(root='gripper',label=label,metadataSha256=sha(meta),imageSha256=sha(image)))
            request = dict(label=label,hostClockId=self.scope['hostClockId'],sources=sources,
                           previews=dict(external=f'{label}-external.png',gripper=f'{label}-gripper.jpg'),
                           sourceEarliest=min(frame['sourceEarliest'],record['sourceEarliest']))
            decision = self.reviewer(copy.deepcopy(request), deadline=deadline, tick=tick)
            require(isinstance(decision,dict) and set(decision) == {'context','stable','onsite'}, 'm4_explicit_camera_review_required')
            result = dict(hostClockId=self.scope['hostClockId'], **sources, **copy.deepcopy(decision))
            name=f'{label}-review.json';self.store.write_json(name,result)
            result.update(evidenceFile=name,evidenceSha256=sha(_read(self.store.root,name)))
            # Both originals must be at least100ms old for the core's RUN guard.
            ready_at=max(frame['stdoutReadAt']+frame['persistenceMs']/1000,record['persistedAt'])+.11
            self._wait(lambda: True if self.clock.monotonic() >= ready_at else None,deadline,tick)
            self.cached=copy.deepcopy(result)
            return result
        except BaseException:
            self.failed=True
            raise

    def latest(self):
        self.check()
        return copy.deepcopy(self.cached)

    def check(self):
        require(self.started and self.closed is None and not self.failed, 'm4_camera_not_active')
        # Nonblocking checks only. Native startup may not yet have a frame.
        with self.recorder.lock:
            require(not self.recorder.fault and not self.recorder.done, 'm4_native_stream_failed')
            if self.recorder.frames: self.recorder.check()
        if self.gripper is not None: self.gripper.check()

    def close(self):
        if self.closed is not None: return copy.deepcopy(self.closed)
        native=gripper=None;errors=[]
        try: native=self.recorder.close() if self.started else None
        except BaseException as exc: errors.append(type(exc).__name__)
        try: gripper=self.gripper.close() if self.gripper is not None else None
        except BaseException as exc: errors.append(type(exc).__name__)
        good=(native is not None and native.get('reason') is None and native.get('clockBridge') is not None
              and native.get('terminalStatus') in ('completed','partial') and not self.failed
              and gripper is not None and gripper.get('status') == 'completed' and not errors)
        self.closed=dict(status='completed' if good else 'failed',native=native,gripper=gripper,errors=errors,
                         controllerWrites=0,automaticRetry=False)
        self.store.write_json('dual-camera-close.json',self.closed)
        return copy.deepcopy(self.closed)
